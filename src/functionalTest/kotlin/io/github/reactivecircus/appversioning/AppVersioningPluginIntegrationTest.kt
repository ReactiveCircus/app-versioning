    @Test
    fun `plugin tasks are not registered for debug builds when releaseBuildOnly is enabled`() {
        initGitRepo(fixtureDir.root)

        val extension = """
            appVersioning {
                releaseBuildOnly.set(true)
            }
        """.trimIndent()
        withFixtureRunner(
            fixtureDir = fixtureDir,
            subprojects = listOf(
                AppProjectTemplate(
                    buildScriptLanguage = buildScriptLanguage,
                    pluginExtension = extension,
                )
            )
        ).runAndCheckResult(
            "tasks",
            "--group=versioning"
        ) {
            assertFalse(output.contains("generateAppVersionInfoForDebug"))
            assertFalse(output.contains("printAppVersionInfoForDebug"))
            assertTrue(
                output.contains(
                    "generateAppVersionInfoForRelease - Generates app's versionCode and versionName based on git tags for the release variant."
                )
            )
            assertTrue(
                output.contains(
                    "printAppVersionInfoForRelease - Prints the versionCode and versionName generated by Android App Versioning plugin (if available) to the console for the release variant."
                )
            )
        }
    }

    @Test
    fun `plugin tasks are not registered when plugin is disabled`() {
        initGitRepo(fixtureDir.root)

        val extension = """
            appVersioning {
                enabled.set(false)
            }
        """.trimIndent()
        withFixtureRunner(
            fixtureDir = fixtureDir,
            subprojects = listOf(
                AppProjectTemplate(
                    buildScriptLanguage = buildScriptLanguage,
                    pluginExtension = extension,
                )
            )
        ).runAndCheckResult(
            "tasks",
            "--group=versioning"
        ) {
            assertFalse(output.contains("Versioning tasks"))
            assertTrue(output.contains("No tasks"))
            assertTrue(output.contains("Android App Versioning plugin is disabled."))
        }
    }

    @Test
    fun `plugin generates versionCode and versionName for the assembled APK when assemble task is run`() {
        initGitRepo(fixtureDir.root) {
            val commitId = commit(message = "1st commit.")
            tag(name = "1.2.3", message = "1st tag", commitId = commitId)
        }

        withFixtureRunner(
            fixtureDir = fixtureDir,
            subprojects = listOf(AppProjectTemplate(buildScriptLanguage = buildScriptLanguage))
        ).runAndCheckResult(
            "assembleRelease"
        ) {
            val versionCodeFileContent = File(
                fixtureDir.root,
                "app/build/outputs/app_versioning/release/version_code.txt"
            ).readText()
            val versionNameFileContent = File(
                fixtureDir.root,
                "app/build/outputs/app_versioning/release/version_name.txt"
            ).readText()
            val apkOutputMetadata = File(
                fixtureDir.root,
                "app/build/outputs/apk/release/output-metadata.json"
            ).readText()

            assertEquals(TaskOutcome.SUCCESS, task(":app:generateAppVersionInfoForRelease")?.outcome)
            assertEquals(TaskOutcome.SUCCESS, task(":app:assembleRelease")?.outcome)

            assertTrue(output.contains("Generated app version code: 10203."))
            assertTrue(output.contains("Generated app version name: \"1.2.3\"."))

            assertEquals("10203", versionCodeFileContent)
            assertEquals("1.2.3", versionNameFileContent)
            assertTrue(apkOutputMetadata.contains("\"versionCode\": 10203"))
            assertTrue(apkOutputMetadata.contains("\"versionName\": \"1.2.3\""))
        }
    }

    @Test
    fun `plugin generates versionCode and versionName for all assembled APKs when splits-APKs and universal APK are enabled`() {
        initGitRepo(fixtureDir.root) {
            val commitId = commit(message = "1st commit.")
            tag(name = "1.2.3", message = "1st tag", commitId = commitId)
        }

        withFixtureRunner(
            fixtureDir = fixtureDir,
            subprojects = listOf(
                AppProjectTemplate(
                    buildScriptLanguage = buildScriptLanguage,
                    splitsApks = true,
                    universalApk = true,
                )
            )
        ).runAndCheckResult(
            "assembleRelease"
        ) {
            val versionCodeFileContent = File(
                fixtureDir.root,
                "app/build/outputs/app_versioning/release/version_code.txt"
            ).readText()
            val versionNameFileContent = File(
                fixtureDir.root,
                "app/build/outputs/app_versioning/release/version_name.txt"
            ).readText()
            val apkOutputMetadata = File(
                fixtureDir.root,
                "app/build/outputs/apk/release/output-metadata.json"
            ).readText()

            assertEquals(TaskOutcome.SUCCESS, task(":app:generateAppVersionInfoForRelease")?.outcome)
            assertEquals(TaskOutcome.SUCCESS, task(":app:assembleRelease")?.outcome)

            assertTrue(output.contains("Generated app version code: 10203."))
            assertTrue(output.contains("Generated app version name: \"1.2.3\"."))

            assertEquals("10203", versionCodeFileContent)
            assertEquals("1.2.3", versionNameFileContent)
            val expectedOutputsCount = 5
            assertEquals(expectedOutputsCount, "\"versionCode\": 10203".toRegex().findAll(apkOutputMetadata).count())
            assertEquals(
                expectedOutputsCount,
                "\"versionName\": \"1.2.3\"".toRegex().findAll(apkOutputMetadata).count()
            )
        }
    }

