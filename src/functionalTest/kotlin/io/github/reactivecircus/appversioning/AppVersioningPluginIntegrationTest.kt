@Burst
class AppVersioningPluginIntegrationTest(
    private val buildScriptLanguage: BuildScriptLanguage = BuildScriptLanguage.Kts,
) {
    @get:Rule
    val fixtureDir = TemporaryFolder()

    @Test
    fun `plugin cannot be applied to project without Android App plugin`() {
        initGitRepo(fixtureDir.root)

        withFixtureRunner(
            fixtureDir = fixtureDir,
            subprojects = listOf(LibraryProjectTemplate(buildScriptLanguage = buildScriptLanguage))
        ).runAndExpectFailure(
            "help"
        ) {
            assertNull(task("help")?.outcome)
            assertTrue(
                output.contains(
                    "Android App Versioning plugin should only be applied to an Android Application project but project ':library' doesn't have the 'com.android.application' plugin applied."
                )
            )
        }
    }

    @Test
    fun `plugin tasks are registered for Android App project without product flavors`() {
        initGitRepo(fixtureDir.root)

        withFixtureRunner(
            fixtureDir = fixtureDir,
            subprojects = listOf(AppProjectTemplate(buildScriptLanguage = buildScriptLanguage))
        ).runAndCheckResult(
            "tasks",
            "--group=versioning"
        ) {
            assertTrue(output.contains("Versioning tasks"))
            assertTrue(
                output.contains(
                    "generateAppVersionInfoForDebug - Generates app's versionCode and versionName based on git tags for the debug variant."
                )
            )
            assertTrue(
                output.contains(
                    "generateAppVersionInfoForRelease - Generates app's versionCode and versionName based on git tags for the release variant."
                )
            )
            assertTrue(
                output.contains(
                    "printAppVersionInfoForDebug - Prints the versionCode and versionName generated by Android App Versioning plugin (if available) to the console for the debug variant."
                )
            )
            assertTrue(
                output.contains(
                    "printAppVersionInfoForRelease - Prints the versionCode and versionName generated by Android App Versioning plugin (if available) to the console for the release variant."
                )
            )
        }
    }

